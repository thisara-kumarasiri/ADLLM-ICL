"""
Run all example-selection methods used in the study.

Each method selects an equal number of Alzheimer's disease (AD)
and cognitively normal (CN) training subjects for every test subject.

Methods
-------
1. Random
2. Cosine similarity
3. Euclidean distance
4. Delta-KNN
5. Proposed LR-weighted XGBoost shared-path gain method

Input
-----
Fixed training and test splits generated by 03_create_data_split.py.

Output
------
One CSV per selection method:

    Test_Subject, AD1, AD2, CN1, CN2

The same training pool and test subjects are used for every method.
"""

from pathlib import Path
import json

import pandas as pd

import Settings as cfg

from Baseline_methods.delta_knn.deltaknn import (
    extract_example,
    prepare_target_examples as prepare_delta_knn_examples,
)

from Baseline_methods.feature_baselines import (
    prepare_target_examples as prepare_feature_baseline_examples,
)

from proposed_method.selector import (
    LRWeightedXGBoostPathGainSelector,
)

# ============================================================
# CONSTANTS
# ============================================================

SUBJECT_COLUMN = "Subject"
GROUP_COLUMN = "Group"

AD_LABEL = "AD"
CN_LABEL = "CN"

VALID_METHODS = [
    "random",
    "cosine",
    "euclidean",
    "delta_knn",
    "lr_weighted_xgboost_path_gain",
]

# ============================================================
# LOAD DATA
# ============================================================

def load_data():
    """
    Load the fixed training and test datasets using the common
    subject representation used by the selection methods.

    Each subject is represented as:

        {
            "name": subject ID,
            "gold": AD or CN,
            "sex": ...,
            "age": ...,
            "features": np.array(...),
            "feature_dict": {...}
        }
    """

    train_docs = extract_example(
        cfg.DATA_SPLIT_DIR / "train.csv"
    )

    test_docs = extract_example(
        cfg.DATA_SPLIT_DIR / "test.csv"
    )

    if not train_docs:
        raise ValueError(
            "No training subjects were loaded."
        )

    if not test_docs:
        raise ValueError(
            "No test subjects were loaded."
        )

    # --------------------------------------------------------
    # Check feature consistency
    # --------------------------------------------------------

    train_feature_names = list(
        train_docs[0]["feature_dict"].keys()
    )

    test_feature_names = list(
        test_docs[0]["feature_dict"].keys()
    )

    if (
        train_feature_names
        != test_feature_names
    ):
        raise ValueError(
            "Training and test feature columns "
            "do not match or are not in the "
            "same order."
        )

    # --------------------------------------------------------
    # Check subject IDs
    # --------------------------------------------------------

    train_names = [
        str(doc["name"])
        for doc in train_docs
    ]

    test_names = [
        str(doc["name"])
        for doc in test_docs
    ]

    if (
        len(train_names)
        != len(set(train_names))
    ):
        raise ValueError(
            "Duplicate subject IDs found "
            "in training data."
        )

    if (
        len(test_names)
        != len(set(test_names))
    ):
        raise ValueError(
            "Duplicate subject IDs found "
            "in test data."
        )

    # --------------------------------------------------------
    # Ensure train/test are disjoint
    # --------------------------------------------------------

    overlap = (
        set(train_names)
        & set(test_names)
    )

    if overlap:
        raise ValueError(
            "Subjects were found in both the "
            "training and test sets:\n"
            f"{sorted(overlap)}"
        )

    print(
        f"Training subjects: {len(train_docs)}"
    )

    print(
        f"Test subjects: {len(test_docs)}"
    )

    print(
        f"Features: {len(train_feature_names)}"
    )

    return (
        train_docs,
        test_docs,
    )

# ============================================================
# RANDOM / COSINE / EUCLIDEAN
# ============================================================

def run_feature_baseline(
    method,
    train_docs,
    test_docs,
):
    """
    Run one of the standard feature-space example-selection
    baselines.
    """

    valid_methods = {
        "random",
        "cosine",
        "euclidean",
    }

    if method not in valid_methods:
        raise ValueError(
            f"Unsupported feature baseline: "
            f"{method}"
        )

    print(
        f"\nRunning selection method: "
        f"{method}"
    )

    selected_batches = (
        prepare_feature_baseline_examples(
            train_docs=train_docs,
            test_docs=test_docs,
            method=method,
            n_shot=cfg.N_SHOT,
        )
    )

    return selected_batches

# ============================================================
