# ============================================================
# CONSTANTS
# ============================================================

SUBJECT_COLUMN = "Subject"
TARGET_COLUMN = "Group"

LABEL_MAPPING = {
    "CN": 0,
    "AD": 1,
}

REVERSE_LABEL_MAPPING = {
    0: "CN",
    1: "AD",
}

# ============================================================
# LOAD DATA
# ============================================================

def load_splits():

    train_df = pd.read_csv(
        cfg.DATA_SPLIT_DIR / "train.csv"
    )

    val_df = pd.read_csv(
        cfg.DATA_SPLIT_DIR / "val.csv"
    )

    test_df = pd.read_csv(
        cfg.DATA_SPLIT_DIR / "test.csv"
    )

    print("Train shape:", train_df.shape)
    print("Validation shape:", val_df.shape)
    print("Test shape:", test_df.shape)

    return train_df, val_df, test_df

# ============================================================
# PREPARE DATA
# ============================================================

def prepare_data(
    train_df,
    val_df,
    test_df,
):

    feature_columns = [
        column
        for column in train_df.columns
        if column not in [
            SUBJECT_COLUMN,
            TARGET_COLUMN,
        ]
    ]

    # --------------------------------------------------------
    # Ensure validation/test contain same features
    # --------------------------------------------------------
    
    for split_name, dataframe in [
        ("validation", val_df),
        ("test", test_df),
    ]:

        missing_columns = [
            column
            for column in feature_columns
            if column not in dataframe.columns
        ]

        if missing_columns:
            raise ValueError(
                f"{split_name} data is missing columns: "
                f"{missing_columns}"
            )

    X_train = train_df[
        feature_columns
    ].copy()

    X_val = val_df[
        feature_columns
    ].copy()

    X_test = test_df[
        feature_columns
    ].copy()

    y_train = train_df[
        TARGET_COLUMN
    ].map(LABEL_MAPPING)

    y_val = val_df[
        TARGET_COLUMN
    ].map(LABEL_MAPPING)

    y_test = test_df[
        TARGET_COLUMN
    ].map(LABEL_MAPPING)

    for split_name, labels in [
        ("training", y_train),
        ("validation", y_val),
        ("test", y_test),
    ]:

        if labels.isna().any():
            raise ValueError(
                f"{split_name} contains unexpected Group values. "
                "Expected only CN and AD."
            )

    y_train = y_train.astype(int)
    y_val = y_val.astype(int)
    y_test = y_test.astype(int)

    return (
        X_train,
        X_val,
        X_test,
        y_train,
        y_val,
        y_test,
        feature_columns,
    )

# ============================================================
# PREPROCESSOR
# ============================================================

def create_preprocessor(
    X_train,
    feature_columns,
):

    numeric_columns = (
        X_train
        .select_dtypes(include="number")
        .columns
        .tolist()
    )

    categorical_columns = [
        column
        for column in feature_columns
        if column not in numeric_columns
    ]

    print(
        "Numeric features:",
        len(numeric_columns),
    )

    print(
        "Categorical features:",
        categorical_columns,
    )

    numeric_pipeline = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="median"
                ),
            ),
            (
                "scaler",
                StandardScaler(),
            ),
        ]
    )

    categorical_pipeline = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="most_frequent"
                ),
            ),
            (
                "encoder",
                OneHotEncoder(
                    handle_unknown="ignore",
                    drop=None,
                ),
            ),
        ]
    )

    return ColumnTransformer(
        transformers=[
            (
                "numeric",
                numeric_pipeline,
                numeric_columns,
            ),
            (
                "categorical",
                categorical_pipeline,
                categorical_columns,
            ),
        ],
        remainder="drop",
    )

# ============================================================
# EVALUATION
# ============================================================

def evaluate_model(
    model,
    X,
    y,
    split_name,
):

    predictions = model.predict(X)

    probabilities = model.predict_proba(X)

    accuracy = accuracy_score(
        y,
        predictions,
    )

    auc = roc_auc_score(
        y,
        probabilities[:, 1],
    )

    print(
        f"\n{split_name} accuracy: "
        f"{accuracy:.4f}"
    )

    print(
        f"{split_name} ROC AUC: "
        f"{auc:.4f}"
    )

    print(
        f"\n{split_name} confusion matrix:"
    )

    print(
        confusion_matrix(
            y,
            predictions,
        )
    )

    print(
        f"\n{split_name} classification report:"
    )

    print(
        classification_report(
            y,
            predictions,
            target_names=[
                "CN",
                "AD",
            ],
            zero_division=0,
        )
    )

    return predictions, probabilities

# ============================================================
# SAVE TEST PREDICTIONS
# ============================================================

def save_test_predictions(
    test_df,
    predictions,
    probabilities,
    output_path,
):

    predictions_df = pd.DataFrame({
        "Subject":
            test_df[SUBJECT_COLUMN],

        "Actual_Group":
            test_df[TARGET_COLUMN],

        "Predicted_Group":
            pd.Series(
                predictions,
                index=test_df.index,
            ).map(
                REVERSE_LABEL_MAPPING
            ),

        "CN_Probability":
            probabilities[:, 0],

        "AD_Probability":
            probabilities[:, 1],
    })

    predictions_df["Correct"] = (
        predictions_df["Actual_Group"]
        == predictions_df["Predicted_Group"]
    )

    predictions_df.to_csv(
        output_path,
        index=False,
    )

# ============================================================
# LOGISTIC REGRESSION
# ============================================================

def train_logistic_regression(
    X_train,
    y_train,
    preprocessor,
):

    model = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor,
            ),
            (
                "classifier",
                LogisticRegression(
                    penalty="l2",
                    C=1.0,
                    solver="liblinear",
                    class_weight="balanced",
                    max_iter=5000,
                    random_state=42,
                ),
            ),
        ]
    )

    model.fit(
        X_train,
        y_train,
    )

    return model

# ============================================================
# LOGISTIC FEATURE IMPORTANCE
# ============================================================

def save_logistic_feature_importance(
    model,
    output_path,
):

    preprocessor = model.named_steps[
        "preprocessor"
    ]

    classifier = model.named_steps[
        "classifier"
    ]

    feature_names = (
        preprocessor
        .get_feature_names_out()
    )

    coefficients = (
        classifier.coef_[0]
    )

    importance_df = pd.DataFrame({
        "Transformed_Feature":
            feature_names,

        "Coefficient":
            coefficients,

        "Absolute_Coefficient":
            np.abs(coefficients),
    })

    importance_df["Feature"] = (
        importance_df[
            "Transformed_Feature"
        ]
        .str.replace(
            r"^(numeric|categorical)__",
            "",
            regex=True,
        )
    )

    total_importance = (
        importance_df[
            "Absolute_Coefficient"
        ].sum()
    )

    if total_importance > 0:

        importance_df[
            "Normalised_Weight"
        ] = (
            importance_df[
                "Absolute_Coefficient"
            ]
            / total_importance
        )

    else:

        importance_df[
            "Normalised_Weight"
        ] = 0.0

    importance_df = (
        importance_df
        .sort_values(
            "Normalised_Weight",
            ascending=False,
        )
        .reset_index(drop=True)
    )

    importance_df["Rank"] = (
        np.arange(
            1,
            len(importance_df) + 1,
        )
    )

    importance_df = importance_df[
        [
            "Rank",
            "Feature",
            "Transformed_Feature",
            "Coefficient",
            "Absolute_Coefficient",
            "Normalised_Weight",
        ]
    ]

    importance_df.to_csv(
        output_path,
        index=False,
    )

# ============================================================
# XGBOOST
# ============================================================

def train_xgboost(
    X_train,
    y_train,
    preprocessor,
):

    training_sample_weights = (
        compute_sample_weight(
            class_weight="balanced",
            y=y_train,
        )
    )

    classifier = xgb.XGBClassifier(
        objective="binary:logistic",
        eval_metric="logloss",
        n_estimators=500,
        max_depth=4,
        learning_rate=0.03,
        subsample=0.8,
        colsample_bytree=0.8,
        gamma=0.0,
        min_child_weight=1,
        reg_alpha=0.0,
        reg_lambda=1.0,
        tree_method="hist",
        importance_type="gain",
        random_state=42,
        n_jobs=-1,
    )

    model = Pipeline(
        steps=[
            (
                "preprocessor",
                preprocessor,
            ),
            (
                "classifier",
                classifier,
            ),
        ]
    )

    model.fit(
        X_train,
        y_train,
        classifier__sample_weight=(
            training_sample_weights
        ),
    )

    return model

# ============================================================
# XGBOOST FEATURE IMPORTANCE
# ============================================================

def save_xgboost_feature_importance(
    model,
    output_path,
):

    preprocessor = model.named_steps[
        "preprocessor"
    ]

    classifier = model.named_steps[
        "classifier"
    ]

    feature_names = (
        preprocessor
        .get_feature_names_out()
    )

    importances = (
        classifier
        .feature_importances_
    )

    if (
        len(feature_names)
        != len(importances)
    ):
        raise ValueError(
            "Feature-name count does not match "
            "XGBoost importance count."
        )

    importance_df = pd.DataFrame({
        "Transformed_Feature":
            feature_names,

        "Gain_Importance":
            importances,
    })

    importance_df["Feature"] = (
        importance_df[
            "Transformed_Feature"
        ]
        .str.replace(
            r"^(numeric|categorical)__",
            "",
            regex=True,
        )
    )

    total_importance = (
        importance_df[
            "Gain_Importance"
        ].sum()
    )

    if total_importance > 0:

        importance_df[
            "Normalised_Weight"
        ] = (
            importance_df[
                "Gain_Importance"
            ]
            / total_importance
        )

    else:

        importance_df[
            "Normalised_Weight"
        ] = 0.0

    importance_df = (
        importance_df
        .sort_values(
            "Normalised_Weight",
            ascending=False,
        )
        .reset_index(drop=True)
    )

    importance_df["Rank"] = (
        np.arange(
            1,
            len(importance_df) + 1,
        )
    )

    importance_df = importance_df[
        [
            "Rank",
            "Feature",
            "Transformed_Feature",
            "Gain_Importance",
            "Normalised_Weight",
        ]
    ]

    importance_df.to_csv(
        output_path,
        index=False,
    )

# ============================================================
# ARGUMENTS
# ============================================================

def parse_args():

    parser = argparse.ArgumentParser(
        description=(
            "Train Logistic Regression and XGBoost models "
            "using the fixed train/validation/test split."
        )
    )

    parser.add_argument(
        "--split-dir",
        type=Path,
        default=cfg.DATA_SPLIT_DIR,
        help=(
            "Directory containing train.csv, val.csv, and test.csv. "
            "Defaults to Settings.DATA_SPLIT_DIR."
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=cfg.ML_MODEL_OUTPUT_ROOT,
        help=(
            "Directory for trained models and associated outputs. "
            "Defaults to Settings.ML_MODEL_OUTPUT_ROOT."
        ),
    )

    return parser.parse_args()

# ============================================================
# MAIN
# ============================================================

def main():

    args = parse_args()

    logistic_dir = (
        args.output_dir
        / "logistic"
    )

    xgboost_dir = (
        args.output_dir
        / "xgboost"
    )

    logistic_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    xgboost_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # Load fixed split
    # --------------------------------------------------------

    (
        train_df,
        val_df,
        test_df,
    ) = load_splits(
        args.split_dir
    )

    (
        X_train,
        X_val,
        X_test,
        y_train,
        y_val,
        y_test,
        feature_columns,
    ) = prepare_data(
        train_df,
        val_df,
        test_df,
    )

    # --------------------------------------------------------
    # LOGISTIC REGRESSION
    # --------------------------------------------------------

    print(
        "TRAINING LOGISTIC REGRESSION"
    )


    logistic_preprocessor = (
        create_preprocessor(
            X_train,
            feature_columns,
        )
    )

    logistic_model = (
        train_logistic_regression(
            X_train,
            y_train,
            logistic_preprocessor,
        )
    )

    joblib.dump(
        logistic_model,
        logistic_dir
        / "logistic_regression_model.pkl",
    )

    evaluate_model(
        logistic_model,
        X_val,
        y_val,
        "Validation",
    )

    (
        logistic_predictions,
        logistic_probabilities,
    ) = evaluate_model(
        logistic_model,
        X_test,
        y_test,
        "Test",
    )

    save_test_predictions(
        test_df,
        logistic_predictions,
        logistic_probabilities,
        logistic_dir
        / "test_predictions.csv",
    )

    save_logistic_feature_importance(
        logistic_model,
        logistic_dir
        / "feature_importance.csv",
    )

    # --------------------------------------------------------
    # XGBOOST
    # --------------------------------------------------------

    print(
        "TRAINING XGBOOST"
    )

    xgboost_preprocessor = (
        create_preprocessor(
            X_train,
            feature_columns,
        )
    )

    xgboost_model = train_xgboost(
        X_train,
        y_train,
        xgboost_preprocessor,
    )

    joblib.dump(
        xgboost_model,
        xgboost_dir
        / "xgboost_model.pkl",
    )

    evaluate_model(
        xgboost_model,
        X_val,
        y_val,
        "Validation",
    )

    (
        xgb_predictions,
        xgb_probabilities,
    ) = evaluate_model(
        xgboost_model,
        X_test,
        y_test,
        "Test",
    )

    save_test_predictions(
        test_df,
        xgb_predictions,
        xgb_probabilities,
        xgboost_dir
        / "test_predictions.csv",
    )

    save_xgboost_feature_importance(
        xgboost_model,
        xgboost_dir
        / "xgboost_feature_weights.csv",
    )

    print(
        "\nML model training completed."
    )


if __name__ == "__main__":
    main()